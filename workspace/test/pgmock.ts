import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";
let db: PGlite | null = null;
export async function getDb() {
  if (!db) {
    db = new PGlite();
    await db.exec(readFileSync(new URL("./crm.sql", import.meta.url), "utf8"));
    await db.exec(readFileSync(new URL("./email.sql", import.meta.url), "utf8"));
    await db.exec(readFileSync(new URL("../migrations/005_supplier.sql", import.meta.url), "utf8"));
    await db.exec(readFileSync(new URL("../migrations/006_katalog.sql", import.meta.url), "utf8"));
    await db.exec(readFileSync(new URL("../migrations/007_compliance.sql", import.meta.url), "utf8"));
    await db.exec(readFileSync(new URL("../migrations/008_campaigns.sql", import.meta.url), "utf8"));
    await db.exec(`CREATE TABLE IF NOT EXISTS audit_log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor TEXT NOT NULL, action TEXT NOT NULL, resource_type TEXT NOT NULL, resource_id TEXT, request_id TEXT, ok BOOLEAN NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now())`);
  }
  return db;
}
function build(strings: TemplateStringsArray, vals: unknown[]) {
  let text = ""; strings.forEach((s, i) => { text += s + (i < vals.length ? `$${i + 1}` : ""); });
  return { text, vals };
}
export function makeNeon() {
  const sql: any = (strings: TemplateStringsArray, ...vals: unknown[]) => {
    const q = build(strings, vals);
    return { __q: q, then: (res: any, rej: any) => getDb().then((d) => d.query(q.text, q.vals as any[])).then((r) => r.rows).then(res, rej) };
  };
  sql.transaction = async (qs: any[]) => { const d = await getDb(); return d.transaction(async (tx) => { const out = []; for (const x of qs) out.push((await tx.query(x.__q.text, x.__q.vals)).rows); return out; }); };
  return sql;
}
