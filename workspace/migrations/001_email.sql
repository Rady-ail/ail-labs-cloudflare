-- AIL LABS Email Module
-- PostgreSQL 15+
-- Idempotent baseline schema. Run through a reviewed migration process.
-- No email sending or external provider integration is performed by this SQL.

CREATE TABLE IF NOT EXISTS contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name TEXT NOT NULL,
    email TEXT NOT NULL,
    organization TEXT,
    contact_type TEXT NOT NULL DEFAULT 'other'
        CHECK (contact_type IN ('supplier', 'clinic', 'internal', 'other')),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS contacts_email_lower_uidx
    ON contacts (LOWER(email));

CREATE TABLE IF NOT EXISTS email_threads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_thread_id TEXT UNIQUE,
    subject TEXT NOT NULL DEFAULT '(No subject)',
    folder TEXT NOT NULL DEFAULT 'inbox'
        CHECK (folder IN ('inbox', 'sent', 'drafts', 'archive')),
    contact_id BIGINT REFERENCES contacts(id) ON DELETE SET NULL,
    snippet TEXT,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    is_starred BOOLEAN NOT NULL DEFAULT FALSE,
    is_archived BOOLEAN NOT NULL DEFAULT FALSE,
    needs_approval BOOLEAN NOT NULL DEFAULT FALSE,
    last_message_at TIMESTAMPTZ,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS email_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id BIGINT NOT NULL
        REFERENCES email_threads(id) ON DELETE CASCADE,
    resend_email_id TEXT UNIQUE,
    direction TEXT NOT NULL
        CHECK (direction IN ('inbound', 'outbound')),
    from_email TEXT NOT NULL,
    to_recipients JSONB NOT NULL DEFAULT '[]'::jsonb,
    cc_recipients JSONB NOT NULL DEFAULT '[]'::jsonb,
    bcc_recipients JSONB NOT NULL DEFAULT '[]'::jsonb,
    subject TEXT NOT NULL DEFAULT '(No subject)',
    body_text TEXT,
    body_html TEXT,
    in_reply_to TEXT,
    references_header TEXT,
    received_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    headers JSONB NOT NULL DEFAULT '{}'::jsonb,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS email_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL
        REFERENCES email_messages(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    content_type TEXT,
    byte_size BIGINT CHECK (byte_size IS NULL OR byte_size >= 0),
    storage_key TEXT,
    provider_attachment_id TEXT,
    checksum_sha256 TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS email_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id BIGINT REFERENCES email_threads(id) ON DELETE SET NULL,
    subject TEXT NOT NULL DEFAULT '(No subject)',
    to_recipients JSONB NOT NULL DEFAULT '[]'::jsonb,
    cc_recipients JSONB NOT NULL DEFAULT '[]'::jsonb,
    bcc_recipients JSONB NOT NULL DEFAULT '[]'::jsonb,
    body_text TEXT NOT NULL DEFAULT '',
    body_html TEXT,
    status TEXT NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'needs_ok', 'scheduled', 'sent', 'cancelled')),
    requested_by TEXT,
    approved_by TEXT,
    approved_at TIMESTAMPTZ,
    scheduled_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    sent_message_id BIGINT REFERENCES email_messages(id) ON DELETE SET NULL,
    idempotency_key TEXT UNIQUE,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS email_labels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    color TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS email_thread_labels (
    thread_id BIGINT NOT NULL
        REFERENCES email_threads(id) ON DELETE CASCADE,
    label_id BIGINT NOT NULL
        REFERENCES email_labels(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (thread_id, label_id)
);

CREATE TABLE IF NOT EXISTS email_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id BIGINT REFERENCES email_threads(id) ON DELETE SET NULL,
    draft_id BIGINT REFERENCES email_drafts(id) ON DELETE SET NULL,
    event_type TEXT NOT NULL,
    actor TEXT,
    event_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS email_suppressions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    reason TEXT NOT NULL,
    source TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS email_suppressions_email_lower_uidx
    ON email_suppressions (LOWER(email));

CREATE INDEX IF NOT EXISTS email_threads_folder_last_message_idx
    ON email_threads (folder, last_message_at DESC);

CREATE INDEX IF NOT EXISTS email_threads_contact_idx
    ON email_threads (contact_id);

CREATE INDEX IF NOT EXISTS email_messages_thread_received_idx
    ON email_messages (thread_id, received_at DESC);

CREATE INDEX IF NOT EXISTS email_attachments_message_idx
    ON email_attachments (message_id);

CREATE INDEX IF NOT EXISTS email_drafts_status_updated_idx
    ON email_drafts (status, updated_at DESC);

CREATE INDEX IF NOT EXISTS email_events_thread_created_idx
    ON email_events (thread_id, created_at DESC);

CREATE INDEX IF NOT EXISTS email_messages_search_idx
    ON email_messages
    USING GIN (
        TO_TSVECTOR(
            'simple',
            COALESCE(subject, '') || ' ' || COALESCE(body_text, '')
        )
    );

CREATE OR REPLACE FUNCTION email_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS contacts_updated_at_trigger ON contacts;
CREATE TRIGGER contacts_updated_at_trigger
BEFORE UPDATE ON contacts
FOR EACH ROW EXECUTE FUNCTION email_set_updated_at();

DROP TRIGGER IF EXISTS email_threads_updated_at_trigger ON email_threads;
CREATE TRIGGER email_threads_updated_at_trigger
BEFORE UPDATE ON email_threads
FOR EACH ROW EXECUTE FUNCTION email_set_updated_at();

DROP TRIGGER IF EXISTS email_drafts_updated_at_trigger ON email_drafts;
CREATE TRIGGER email_drafts_updated_at_trigger
BEFORE UPDATE ON email_drafts
FOR EACH ROW EXECUTE FUNCTION email_set_updated_at();

COMMENT ON TABLE contacts IS
    'Email contacts; store only necessary business contact information.';

COMMENT ON TABLE email_threads IS
    'Conversation grouping and mailbox state.';

COMMENT ON TABLE email_messages IS
    'Inbound and outbound message records; resend_email_id prevents duplicate ingestion.';

COMMENT ON TABLE email_attachments IS
    'Attachment metadata; storage_key references controlled private storage.';

COMMENT ON TABLE email_drafts IS
    'Draft approval lifecycle. A status change alone must never trigger an external send.';

COMMENT ON TABLE email_events IS
    'Append-only audit trail for review, approval, cancellation, and mailbox actions.';

COMMENT ON TABLE email_suppressions IS
    'Addresses excluded from future outbound campaigns or operational sends.';
